#!/usr/bin/env python3
"""
Tests of the update kit (guncelleyici/kit) with real processes and files:

- the audit hook records what a script opens, lists and starts under T870-araclar, and nothing
  outside it
- the record turns into kit contents: files as they are, listed directories whole, evidence and
  caches never
- the kit's contents list (icerik.txt, generated by kit-uret.py denetle) names only files that exist,
  and the kit takes every source a prebuilt binary's out/STAMP hashes
- the tablet's SDK stand-ins run the SDK's own jars and Debian's native tools
"""
import importlib.util
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
KIT_DIR = os.path.join(os.path.dirname(HERE), "kit")
TOOLS_DIR = os.path.dirname(os.path.dirname(HERE))


def load_kit():
    spec = importlib.util.spec_from_file_location("kit_uret", os.path.join(KIT_DIR, "kit-uret.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


class Hook(unittest.TestCase):
    def test_records_reads_inside_tools_only(self):
        with tempfile.TemporaryDirectory(dir=os.path.join(TOOLS_DIR, "guncelleyici", "kit")) as d:
            target = os.path.join(d, "okunan.txt")
            with open(target, "w") as f:
                f.write("x")
            script = os.path.join(d, "betik.py")
            with open(script, "w") as f:
                f.write(
                    "import os, subprocess, sys\n"
                    f"open({target!r}).read()\n"
                    "open('/etc/hostname').read()\n"
                    f"os.listdir({d!r})\n"
                    f"subprocess.run(['cat', {target!r}], stdout=subprocess.DEVNULL)\n")
            kayit = os.path.join(d, "kayit.txt")
            subprocess.run([sys.executable, os.path.join(KIT_DIR, "denetim_kancasi.py"), kayit, script],
                           check=True)
            with open(kayit) as f:
                lines = set(f.read().splitlines())
            rel = os.path.relpath(target, TOOLS_DIR)
            self.assertIn(f"open {rel}", lines)
            self.assertIn(f"list {os.path.relpath(d, TOOLS_DIR)}", lines)
            self.assertIn(f"exec {rel}", lines)
            self.assertFalse([l for l in lines if "hostname" in l])

    def test_record_to_contents(self):
        kit = load_kit()
        with tempfile.TemporaryDirectory(dir=os.path.join(TOOLS_DIR, "guncelleyici", "kit")) as d:
            os.makedirs(os.path.join(d, "alt", "kanit"))
            os.makedirs(os.path.join(d, "alt", "__pycache__"))
            for p in ("a.txt", "alt/b.txt", "alt/kanit/c.txt", "alt/__pycache__/d.pyc"):
                open(os.path.join(d, p), "w").close()
            rd = os.path.relpath(d, TOOLS_DIR)
            kayit = os.path.join(d, "kayit.txt")
            with open(kayit, "w") as f:
                f.write(f"open {rd}/a.txt\nlist {rd}/alt\nopen {rd}/yok.txt\nlist .\n")
            got = kit.icerik_from_record(kayit)
            self.assertEqual(got, sorted([f"{rd}/a.txt", f"{rd}/alt/b.txt"]))


class Contents(unittest.TestCase):
    def test_icerik_names_existing_files(self):
        kit = load_kit()
        if not os.path.isfile(kit.ICERIK):
            self.skipTest("icerik.txt not generated yet (kit-uret.py denetle)")
        missing = [f for f in kit.read_icerik() if not os.path.isfile(os.path.join(TOOLS_DIR, f))]
        self.assertEqual(missing, [])

    def test_icerik_names_nothing_per_checkout(self):
        """A user with another release or LineageOS zip, or without the author's headers, has
        the same content list (H, 31 Oct: the list named the author's .273 partitions)."""
        kit = load_kit()
        if not os.path.isfile(kit.ICERIK):
            self.skipTest("icerik.txt not generated yet (kit-uret.py denetle)")
        self.assertEqual([f for f in kit.read_icerik() if kit.per_checkout(f)], [])

    def test_stamped_sources_in_kit(self):
        kit = load_kit()
        if not os.path.isfile(kit.ICERIK):
            self.skipTest("icerik.txt not generated yet (kit-uret.py denetle)")
        files = set(kit.kit_files())
        for d in kit.STAMPED:
            if not os.path.isdir(os.path.join(TOOLS_DIR, d)):
                continue
            for f in kit.tracked(d):
                if not kit.skipped(f):
                    self.assertIn(f, files)
        for e in kit.ENTRY:
            self.assertIn(e, files)
        # No device log or evidence (the replay reads selinux/reddedilenler.txt), never the
        # downloaded release or the LineageOS zip; every stored super header the checkout knows.
        self.assertFalse([f for f in files if f.startswith("acilis-loglari/") or "/kanit/" in f])
        self.assertIn("selinux/reddedilenler.txt", files)
        self.assertLessEqual(kit.header_files(), files)
        self.assertIn("super-baslik/lineage.bin.xz", kit.header_files())
        self.assertFalse([f for f in files if f.startswith(kit.EXCLUDE_PREFIXES)])


class Wrappers(unittest.TestCase):
    def test_wrappers_point_at_jars_and_debian_tools(self):
        kit = load_kit()
        self.assertIn("d8.jar", kit.WRAPPERS["d8"])
        self.assertIn("com.android.tools.r8.D8", kit.WRAPPERS["d8"])
        self.assertIn("apksigner.jar", kit.WRAPPERS["apksigner"])
        for name in ("zipalign", "dexdump"):
            self.assertIn(f"/usr/bin/{name}", kit.WRAPPERS[name])

    def test_d8_jar_runs_through_wrapper(self):
        kit = load_kit()
        jar = os.path.join(kit.BUILD_TOOLS, "lib", "d8.jar")
        if not os.path.isfile(jar):
            self.skipTest(f"{jar} missing")
        with tempfile.TemporaryDirectory() as d:
            os.makedirs(os.path.join(d, "lib"))
            os.symlink(jar, os.path.join(d, "lib", "d8.jar"))
            w = os.path.join(d, "d8")
            with open(w, "w") as f:
                f.write("#!/bin/sh\n" + kit.WRAPPERS["d8"] + "\n")
            os.chmod(w, 0o755)
            r = subprocess.run([w, "--version"], capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr)
            self.assertIn("D8", r.stdout + r.stderr)


if __name__ == "__main__":
    unittest.main()
